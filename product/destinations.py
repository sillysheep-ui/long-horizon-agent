_EXTRA = tuple(DESTINATIONS) + tuple(LATIN_ALIASES.keys())


def _base(name: str) -> str:
    text = re.sub(r"[\s'’·,，.。()（）\-]", "", str(name or "")).lower()
    for suffix in SUFFIXES:
        if text.endswith(suffix):
            text = text[: -len(suffix)]
            break
    return text


def known_destination(name: str, known: Iterable[str] | None = None) -> bool:
    """判断一个目的地是否在白名单内（容忍“杭州市”“Hangzhou”这类写法）。"""
    base = _base(name)
    if not base:
        return False
    pool = known if known is not None else _EXTRA
    for item in pool:
        if base == _base(item):
            return True
    return base in LATIN_ALIASES


def unknown_destinations(values: Iterable[str], known: Iterable[str] | None = None) -> list[str]:
    return [item for item in values if item and not known_destination(item, known)]
